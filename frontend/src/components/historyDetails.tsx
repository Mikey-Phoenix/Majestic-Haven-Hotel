import { Badge } from "./ui/badge";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "./ui/dialog";
import type { Booking } from "./types/booking";
import { formatDate, nightsBetween, statusStyles } from "./utils/booking";

interface Props {
  booking: Booking;
  open: boolean;
  onOpenChange: (open: boolean) => void;
}

function BookingDetailsDialog({ booking, open, onOpenChange }: Props) {
  const nights = nightsBetween(booking.checkIn, booking.checkOut);
  const canDownloadReceipt = booking.status !== "Cancelled";

  const handleDownloadReceipt = () => {
    // The PDF is generated by the backend. Expected endpoint:
    //   GET /api/bookings/:id/receipt
    //   -> 200, Content-Type: application/pdf, Content-Disposition: attachment
    // With a download header the browser saves the file and stays on this page.
    window.location.href = `/api/bookings/${encodeURIComponent(booking.id)}/receipt`;
  };

  const rows: { label: string; value: string }[] = [
    { label: "Booking reference", value: booking.id },
    { label: "Check-in", value: formatDate(booking.checkIn) },
    { label: "Check-out", value: formatDate(booking.checkOut) },
    { label: "Length of stay", value: `${nights} night${nights === 1 ? "" : "s"}` },
    ...(booking.guests ? [{ label: "Guests", value: String(booking.guests) }] : []),
    { label: "Total", value: booking.total },
    ...(booking.paymentStatus ? [{ label: "Payment", value: booking.paymentStatus }] : []),
  ];

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="bg-white sm:max-w-md">
        <DialogHeader>
          <div className="flex items-center gap-3 pr-6">
            <DialogTitle className="text-2xl font-bold text-[#3f5a42]">{booking.roomName}</DialogTitle>
            <Badge variant="secondary" className={statusStyles[booking.status]}>
              {booking.status}
            </Badge>
          </div>
          <DialogDescription>Details of your stay at Majestic Haven.</DialogDescription>
        </DialogHeader>

        <div className="h-32 w-full rounded-lg bg-[#7a9a77]/40" aria-hidden="true" />

        <dl className="divide-y divide-gray-100 text-sm">
          {rows.map((row) => (
            <div key={row.label} className="flex items-center justify-between gap-4 py-2.5">
              <dt className="text-gray-500">{row.label}</dt>
              <dd className="text-right font-medium text-(--main-text)">{row.value}</dd>
            </div>
          ))}
        </dl>

        {booking.specialRequests && (
          <div className="rounded-lg bg-[#ebf0da]/60 p-3 text-sm">
            <p className="text-xs uppercase tracking-wide text-[#6f9170]">Special requests</p>
            <p className="mt-1 text-(--main-text)">{booking.specialRequests}</p>
          </div>
        )}

        <DialogFooter className="gap-2 sm:gap-2">
          <button
            type="button"
            onClick={() => onOpenChange(false)}
            className="cursor-pointer rounded-full border px-6 py-2.5 text-sm text-[#3f5a42] transition-colors hover:bg-[#ebf0da] focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-[#6f9170]"
          >
            Close
          </button>
          <button
            type="button"
            onClick={handleDownloadReceipt}
            disabled={!canDownloadReceipt}
            title={canDownloadReceipt ? undefined : "No receipt for cancelled bookings"}
            className="cursor-pointer rounded-full bg-[#6f9170] px-6 py-2.5 text-sm text-white transition-colors hover:bg-[#5b7d5d] focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-[#6f9170] disabled:cursor-not-allowed disabled:opacity-50 disabled:hover:bg-[#6f9170]"
          >
            Download receipt (PDF)
          </button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}

export default BookingDetailsDialog;
